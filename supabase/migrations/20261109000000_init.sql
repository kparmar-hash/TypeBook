-- =====================================================================================================
-- Typebook: Supabase schema, security policies and sync functions
--
-- HOW TO RUN: Supabase dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- It is safe to run again later (everything is idempotent) and runs as one transaction, so if any
-- statement fails nothing is applied.
--
-- WHAT IT CREATES
--   notebooks, pages, pdfs      one row per notebook / page / registered PDF, owned by one user
--   save_notebook, save_page    functions the app calls to write; they MERGE with what is already stored
--                               (same rules as the app's offline merge), so two devices never overwrite
--                               each other's edits
--   purge_tombstones            deletes soft-deleted data older than 30 days
--   storage bucket "assets"     private bucket for pasted images, one folder per user
--
-- SECURITY MODEL (read this once)
--   * Every table has Row Level Security ENABLED and FORCED. A signed-in user can only see and change
--     rows whose user_id is their own auth.uid(). Nobody else, including other signed-in users, can.
--   * The `anon` role (anyone holding only the public key and not signed in) has NO access at all.
--   * Storage: each user can only touch objects under a folder named after their own user id.
--   * The app must only ever hold the public/publishable key. The service_role / secret key bypasses RLS
--     and must never be put in the app or in .env.
-- =====================================================================================================

begin;

-- -----------------------------------------------------------------------------------------------------
-- 1. Tables
--    ids are generated by the app (ULIDs), so the primary key is (user_id, id): two users can never
--    collide on, or squat, each other's ids.
-- -----------------------------------------------------------------------------------------------------

create table if not exists public.notebooks (
  user_id     uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  id          text        not null check (id ~ '^nb_[0-9A-Z]{26}$'),
  name        text        not null check (char_length(name) between 1 and 200),
  paper       text        not null default 'ruled'   check (paper in ('blank', 'ruled', 'dots', 'grid')),
  font        text        not null default 'caveat'  check (font in ('caveat', 'kalam', 'patrick', 'sans', 'mono')),
  font_size   integer     not null default 24        check (font_size between 10 and 96),
  ink         text        not null default 'blue'    check (ink in ('black', 'blue', 'red', 'green', 'pencil')),
  margin      boolean     not null default true,
  page_order  text[]      not null default '{}'      check (cardinality(page_order) <= 10000),
  deleted     boolean     not null default false,
  -- updated_at is the CLIENT's edit time (used to decide who wins a merge);
  -- synced_at is the SERVER's write time (used by devices to ask "what changed since I last looked").
  updated_at  timestamptz not null default now(),
  synced_at   timestamptz not null default clock_timestamp(),
  primary key (user_id, id)
);

create table if not exists public.pages (
  user_id      uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  id           text        not null check (id ~ '^pg_[0-9A-Z]{26}$'),
  notebook_id  text        not null,
  title        text        not null default '' check (char_length(title) <= 500),
  paper        text        not null default 'default' check (paper in ('default', 'blank', 'ruled', 'dots', 'grid')),
  tags         text[]      not null default '{}' check (cardinality(tags) <= 100),
  deleted      boolean     not null default false,
  blocks       jsonb       not null default '[]'
                 check (jsonb_typeof(blocks) = 'array' and jsonb_array_length(blocks) <= 20000
                        and octet_length(blocks::text) <= 8000000),
  images       jsonb       not null default '[]'
                 check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 2000
                        and octet_length(images::text) <= 1000000),
  updated_at   timestamptz not null default now(),
  synced_at    timestamptz not null default clock_timestamp(),
  primary key (user_id, id),
  -- the notebook must belong to the same user, so a page can never be attached to someone else's notebook
  foreign key (user_id, notebook_id) references public.notebooks (user_id, id) on delete cascade
);

-- Only the hash (identifies the file on every device) and a display name. Never a file path:
-- locations differ per machine and are kept on the device.
create table if not exists public.pdfs (
  user_id     uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  hash        text        not null check (hash ~ '^[0-9a-f]{32}$'),
  name        text        not null check (char_length(name) between 1 and 255),
  created_at  timestamptz not null default now(),
  primary key (user_id, hash)
);

create index if not exists notebooks_user_synced_idx on public.notebooks (user_id, synced_at);
create index if not exists pages_user_synced_idx     on public.pages (user_id, synced_at);
create index if not exists pages_notebook_idx        on public.pages (user_id, notebook_id);

-- -----------------------------------------------------------------------------------------------------
-- 2. Row Level Security
-- -----------------------------------------------------------------------------------------------------

alter table public.notebooks enable row level security;
alter table public.pages     enable row level security;
alter table public.pdfs      enable row level security;
-- FORCE makes the rules apply even to the table owner (defence in depth).
alter table public.notebooks force row level security;
alter table public.pages     force row level security;
alter table public.pdfs      force row level security;

-- `(select auth.uid())` is evaluated once per query instead of once per row.
drop policy if exists notebooks_select on public.notebooks;
drop policy if exists notebooks_insert on public.notebooks;
drop policy if exists notebooks_update on public.notebooks;
drop policy if exists notebooks_delete on public.notebooks;
create policy notebooks_select on public.notebooks for select to authenticated using (user_id = (select auth.uid()));
create policy notebooks_insert on public.notebooks for insert to authenticated with check (user_id = (select auth.uid()));
create policy notebooks_update on public.notebooks for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy notebooks_delete on public.notebooks for delete to authenticated using (user_id = (select auth.uid()));

drop policy if exists pages_select on public.pages;
drop policy if exists pages_insert on public.pages;
drop policy if exists pages_update on public.pages;
drop policy if exists pages_delete on public.pages;
create policy pages_select on public.pages for select to authenticated using (user_id = (select auth.uid()));
create policy pages_insert on public.pages for insert to authenticated with check (user_id = (select auth.uid()));
create policy pages_update on public.pages for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy pages_delete on public.pages for delete to authenticated using (user_id = (select auth.uid()));

drop policy if exists pdfs_select on public.pdfs;
drop policy if exists pdfs_insert on public.pdfs;
drop policy if exists pdfs_update on public.pdfs;
drop policy if exists pdfs_delete on public.pdfs;
create policy pdfs_select on public.pdfs for select to authenticated using (user_id = (select auth.uid()));
create policy pdfs_insert on public.pdfs for insert to authenticated with check (user_id = (select auth.uid()));
create policy pdfs_update on public.pdfs for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy pdfs_delete on public.pdfs for delete to authenticated using (user_id = (select auth.uid()));

-- Table privileges: signed-in users only. Supabase grants new tables to anon by default; take that away.
revoke all on table public.notebooks, public.pages, public.pdfs from anon, public;
grant select, insert, update, delete on table public.notebooks, public.pages, public.pdfs to authenticated;

-- -----------------------------------------------------------------------------------------------------
-- 3. Triggers: keep identity fixed, stamp the server time, and stop a skewed or hostile clock from
--    putting "updated_at" far in the future (which would win every merge forever).
-- -----------------------------------------------------------------------------------------------------

create or replace function public.tb_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and (new.user_id is distinct from old.user_id or new.id is distinct from old.id) then
    raise exception 'user_id and id cannot be changed' using errcode = '42501';
  end if;
  new.synced_at := clock_timestamp();
  if new.updated_at > now() + interval '1 day' then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create or replace function public.tb_pages_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.notebook_id is distinct from old.notebook_id then
    raise exception 'a page cannot move to another notebook' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists notebooks_touch on public.notebooks;
create trigger notebooks_touch before insert or update on public.notebooks
  for each row execute function public.tb_touch();

drop trigger if exists pages_touch on public.pages;
create trigger pages_touch before insert or update on public.pages
  for each row execute function public.tb_touch();

drop trigger if exists pages_guard on public.pages;
create trigger pages_guard before update on public.pages
  for each row execute function public.tb_pages_guard();

-- -----------------------------------------------------------------------------------------------------
-- 4. Merge helpers (same rules as the app's offline merge)
--      per item id: the newer "updatedAt" wins; on an exact tie a tombstone ("deleted": true) wins;
--      items that exist on only one side are kept.
-- -----------------------------------------------------------------------------------------------------

create or replace function public.tb_iso(ts timestamptz)
returns text
language sql
immutable
set search_path = ''
as $$
  select to_char(ts at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

create or replace function public.tb_merge_items(a jsonb, b jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select coalesce(jsonb_agg(w.item order by w.id), '[]'::jsonb)
  from (
    select distinct on (u.id) u.id, u.item
    from (
      select x ->> 'id' as id, x as item
        from jsonb_array_elements(case when jsonb_typeof(a) = 'array' then a else '[]'::jsonb end) x
       where x ->> 'id' is not null
      union all
      select x ->> 'id', x
        from jsonb_array_elements(case when jsonb_typeof(b) = 'array' then b else '[]'::jsonb end) x
       where x ->> 'id' is not null
    ) u
    order by u.id,
             (u.item ->> 'updatedAt') desc nulls last,
             coalesce(u.item -> 'deleted' = 'true'::jsonb, false) desc,
             u.item::text desc
  ) w
$$;

-- Drop tombstones whose "updatedAt" is older than `cutoff` (an ISO timestamp string).
create or replace function public.tb_prune_items(items jsonb, cutoff text)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select coalesce(jsonb_agg(x.item order by x.ord), '[]'::jsonb)
  from jsonb_array_elements(case when jsonb_typeof(items) = 'array' then items else '[]'::jsonb end)
         with ordinality as x(item, ord)
  where not (coalesce(x.item -> 'deleted' = 'true'::jsonb, false)
             and coalesce(x.item ->> 'updatedAt', '') < cutoff)
$$;

-- -----------------------------------------------------------------------------------------------------
-- 5. save_page / save_notebook
--    SECURITY INVOKER: they run as the signed-in user, so Row Level Security applies to everything they do.
--    The row is locked while merging, so two devices saving at once are applied one after the other.
--    The return value is the merged result in the app's own JSON shape.
-- -----------------------------------------------------------------------------------------------------

create or replace function public.save_page(p_notebook_id text, p_page jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  uid        uuid := auth.uid();
  pid        text := p_page ->> 'id';
  inc_at     timestamptz;
  inc_del    boolean;
  inc_title  text;
  inc_paper  text;
  inc_tags   text[];
  cur        public.pages%rowtype;
  won        boolean;
  res        public.pages%rowtype;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if jsonb_typeof(p_page) is distinct from 'object' then
    raise exception 'page must be a JSON object' using errcode = '22023';
  end if;
  if pid is null or pid !~ '^pg_[0-9A-Z]{26}$' then
    raise exception 'invalid page id' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_page -> 'blocks', '[]'::jsonb)) is distinct from 'array'
     or jsonb_typeof(coalesce(p_page -> 'images', '[]'::jsonb)) is distinct from 'array'
     or jsonb_typeof(coalesce(p_page -> 'tags', '[]'::jsonb)) is distinct from 'array' then
    raise exception 'blocks, images and tags must be arrays' using errcode = '22023';
  end if;

  inc_at    := (p_page ->> 'updatedAt')::timestamptz;
  inc_del   := coalesce((p_page ->> 'deleted')::boolean, false);
  inc_title := coalesce(p_page ->> 'title', '');
  inc_paper := coalesce(p_page ->> 'paper', 'default');
  inc_tags  := array(select jsonb_array_elements_text(coalesce(p_page -> 'tags', '[]'::jsonb)));
  if inc_at is null then
    raise exception 'updatedAt is required' using errcode = '22023';
  end if;

  -- Make sure the row exists (a no-op if it does), then lock it for the merge.
  insert into public.pages (user_id, id, notebook_id, title, paper, tags, deleted, blocks, images, updated_at)
  values (uid, pid, p_notebook_id, inc_title, inc_paper, inc_tags, inc_del,
          coalesce(p_page -> 'blocks', '[]'::jsonb), coalesce(p_page -> 'images', '[]'::jsonb), inc_at)
  on conflict (user_id, id) do nothing;

  select * into cur from public.pages where user_id = uid and id = pid for update;
  if cur.notebook_id <> p_notebook_id then
    raise exception 'that page belongs to a different notebook' using errcode = '42501';
  end if;

  -- Page-level fields (title, tags, paper, deleted) come from whichever page is newer.
  won := inc_at > cur.updated_at or (inc_at = cur.updated_at and inc_del and not cur.deleted);

  update public.pages set
    title      = case when won then inc_title else cur.title end,
    paper      = case when won then inc_paper else cur.paper end,
    tags       = case when won then inc_tags  else cur.tags end,
    deleted    = case when won then inc_del   else cur.deleted end,
    blocks     = public.tb_merge_items(cur.blocks, coalesce(p_page -> 'blocks', '[]'::jsonb)),
    images     = public.tb_merge_items(cur.images, coalesce(p_page -> 'images', '[]'::jsonb)),
    updated_at = greatest(cur.updated_at, inc_at)
  where user_id = uid and id = pid
  returning * into res;

  return jsonb_build_object(
           'schema', 1,
           'id', res.id,
           'title', res.title,
           'paper', res.paper,
           'tags', to_jsonb(res.tags),
           'updatedAt', public.tb_iso(res.updated_at),
           'blocks', res.blocks,
           'images', res.images)
         || case when res.deleted then jsonb_build_object('deleted', true) else '{}'::jsonb end;
end;
$$;

create or replace function public.save_notebook(p_notebook jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  uid        uuid := auth.uid();
  nid        text := p_notebook ->> 'id';
  inc_at     timestamptz;
  inc_del    boolean;
  inc_order  text[];
  cur        public.notebooks%rowtype;
  won        boolean;
  win_order  text[];
  lose_order text[];
  res        public.notebooks%rowtype;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  if jsonb_typeof(p_notebook) is distinct from 'object' then
    raise exception 'notebook must be a JSON object' using errcode = '22023';
  end if;
  if nid is null or nid !~ '^nb_[0-9A-Z]{26}$' then
    raise exception 'invalid notebook id' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_notebook -> 'pageOrder', '[]'::jsonb)) is distinct from 'array' then
    raise exception 'pageOrder must be an array' using errcode = '22023';
  end if;

  inc_at    := (p_notebook ->> 'updatedAt')::timestamptz;
  inc_del   := coalesce((p_notebook ->> 'deleted')::boolean, false);
  inc_order := array(select jsonb_array_elements_text(coalesce(p_notebook -> 'pageOrder', '[]'::jsonb)));
  if inc_at is null then
    raise exception 'updatedAt is required' using errcode = '22023';
  end if;

  insert into public.notebooks (user_id, id, name, paper, font, font_size, ink, margin, page_order, deleted, updated_at)
  values (uid, nid,
          coalesce(p_notebook ->> 'name', 'Untitled notebook'),
          coalesce(p_notebook ->> 'paper', 'ruled'),
          coalesce(p_notebook ->> 'font', 'caveat'),
          coalesce((p_notebook ->> 'fontSize')::integer, 24),
          coalesce(p_notebook ->> 'ink', 'blue'),
          coalesce((p_notebook ->> 'margin')::boolean, true),
          inc_order, inc_del, inc_at)
  on conflict (user_id, id) do nothing;

  select * into cur from public.notebooks where user_id = uid and id = nid for update;

  won := inc_at > cur.updated_at or (inc_at = cur.updated_at and inc_del and not cur.deleted);
  win_order  := case when won then inc_order else cur.page_order end;
  lose_order := case when won then cur.page_order else inc_order end;

  -- The winner's page order, plus any pages only the other side knows about.
  win_order := win_order || array(
    select t.x from unnest(lose_order) with ordinality as t(x, i)
    where t.x <> all (win_order) order by t.i);

  update public.notebooks set
    name       = case when won then coalesce(p_notebook ->> 'name', cur.name) else cur.name end,
    paper      = case when won then coalesce(p_notebook ->> 'paper', cur.paper) else cur.paper end,
    font       = case when won then coalesce(p_notebook ->> 'font', cur.font) else cur.font end,
    font_size  = case when won then coalesce((p_notebook ->> 'fontSize')::integer, cur.font_size) else cur.font_size end,
    ink        = case when won then coalesce(p_notebook ->> 'ink', cur.ink) else cur.ink end,
    margin     = case when won then coalesce((p_notebook ->> 'margin')::boolean, cur.margin) else cur.margin end,
    deleted    = case when won then inc_del else cur.deleted end,
    page_order = win_order,
    updated_at = greatest(cur.updated_at, inc_at)
  where user_id = uid and id = nid
  returning * into res;

  return jsonb_build_object(
           'schema', 1,
           'id', res.id,
           'name', res.name,
           'paper', res.paper,
           'font', res.font,
           'fontSize', res.font_size,
           'ink', res.ink,
           'margin', res.margin,
           'pageOrder', to_jsonb(res.page_order),
           'updatedAt', public.tb_iso(res.updated_at))
         || case when res.deleted then jsonb_build_object('deleted', true) else '{}'::jsonb end;
end;
$$;

-- -----------------------------------------------------------------------------------------------------
-- 6. Clean-up: remove the signed-in user's tombstones older than `p_days` (default 30).
--    Run from the app now and then. (To run it for everyone on a schedule you would enable pg_cron and
--    write a separate admin job; it is deliberately not done here.)
-- -----------------------------------------------------------------------------------------------------

create or replace function public.purge_tombstones(p_days integer default 30)
returns void
language plpgsql
set search_path = ''
as $$
declare
  uid    uuid := auth.uid();
  cutoff timestamptz := now() - make_interval(days => greatest(p_days, 1));
  cut    text := public.tb_iso(now() - make_interval(days => greatest(p_days, 1)));
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  delete from public.notebooks where user_id = uid and deleted and updated_at < cutoff;
  delete from public.pages     where user_id = uid and deleted and updated_at < cutoff;
  update public.pages p set
    blocks = public.tb_prune_items(p.blocks, cut),
    images = public.tb_prune_items(p.images, cut)
  where p.user_id = uid
    and (public.tb_prune_items(p.blocks, cut) is distinct from p.blocks
         or public.tb_prune_items(p.images, cut) is distinct from p.images);
end;
$$;

-- Functions are executable by everyone by default; restrict them to signed-in users.
revoke all on function public.tb_iso(timestamptz)                 from public, anon;
revoke all on function public.tb_merge_items(jsonb, jsonb)        from public, anon;
revoke all on function public.tb_prune_items(jsonb, text)         from public, anon;
revoke all on function public.save_page(text, jsonb)              from public, anon;
revoke all on function public.save_notebook(jsonb)                from public, anon;
revoke all on function public.purge_tombstones(integer)          from public, anon;
grant execute on function public.tb_iso(timestamptz)              to authenticated;
grant execute on function public.tb_merge_items(jsonb, jsonb)     to authenticated;
grant execute on function public.tb_prune_items(jsonb, text)      to authenticated;
grant execute on function public.save_page(text, jsonb)           to authenticated;
grant execute on function public.save_notebook(jsonb)             to authenticated;
grant execute on function public.purge_tombstones(integer)       to authenticated;

-- -----------------------------------------------------------------------------------------------------
-- 7. Live updates between devices (Supabase Realtime). Realtime respects the RLS policies above, so a
--    device only ever receives its own user's changes.
-- -----------------------------------------------------------------------------------------------------

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables
                   where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'pages') then
      alter publication supabase_realtime add table public.pages;
    end if;
    if not exists (select 1 from pg_publication_tables
                   where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'notebooks') then
      alter publication supabase_realtime add table public.notebooks;
    end if;
  end if;
end
$$;

-- -----------------------------------------------------------------------------------------------------
-- 8. Storage: private bucket for pasted images.
--    Object path convention: <user id>/<notebook id>/<asset file name>
--    The policies only allow a user to touch objects inside the folder named after their own user id.
-- -----------------------------------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('assets', 'assets', false, 10485760,
        array['image/png', 'image/jpeg', 'image/gif', 'image/webp'])
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists tb_assets_select on storage.objects;
drop policy if exists tb_assets_insert on storage.objects;
drop policy if exists tb_assets_update on storage.objects;
drop policy if exists tb_assets_delete on storage.objects;

create policy tb_assets_select on storage.objects for select to authenticated
  using (bucket_id = 'assets' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy tb_assets_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'assets' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy tb_assets_update on storage.objects for update to authenticated
  using (bucket_id = 'assets' and (storage.foldername(name))[1] = (select auth.uid())::text)
  with check (bucket_id = 'assets' and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy tb_assets_delete on storage.objects for delete to authenticated
  using (bucket_id = 'assets' and (storage.foldername(name))[1] = (select auth.uid())::text);

commit;

